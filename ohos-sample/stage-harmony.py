#!/usr/bin/env python3
"""Stage the generated HarmonyOS app in an ASCII path accepted by Hvigor."""
from pathlib import Path
import argparse
import shutil

parser = argparse.ArgumentParser()
parser.add_argument("--output", default="/private/tmp/kai-a2ui-harmony")
parser.add_argument("--sdk", default=str(Path.home() / "Library/OpenHarmony/Sdk"))
args = parser.parse_args()
source = Path(__file__).resolve().parent / "harmonyApp"
destination = Path(args.output).absolute()
if not str(destination).isascii():
    raise SystemExit("Hvigor staging output must use an ASCII path")
marker = destination / ".kai-a2ui-stage"
if destination.exists():
    if not marker.exists():
        raise SystemExit(f"Refusing to overwrite an unmarked directory: {destination}")
    shutil.rmtree(destination)
shutil.copytree(source, destination, ignore=shutil.ignore_patterns(".hvigor", "build", ".idea"))
marker.write_text("Generated by ohos-sample/stage-harmony.py\n")
(destination / "local.properties").write_text(f"sdk.dir={Path(args.sdk).absolute()}\n")
print(destination)
